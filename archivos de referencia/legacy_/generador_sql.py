import pandas as pd
import os
import glob
import re

def limpiar_nombre_columna(col):
    """Aplica las mismas reglas de limpieza que tu motor ETL."""
    col = str(col).strip().lower().replace(' ', '_')
    col = col.replace('.', '').replace('(', '').replace(')', '')
    col = col.replace('unnamed:_', 'unnamed_')
    col = col.replace('__', '_')
    
    # Si la columna empieza con un número (ej. 00:00:20), PostgreSQL exige comillas dobles
    if col and col[0].isdigit():
        return f'"{col}"'
    return col

def mapear_tipo_sql(dtype):
    """Convierte los tipos de datos de Pandas a los de PostgreSQL."""
    dtype_str = str(dtype).lower()
    if 'int' in dtype_str:
        return 'bigint'
    elif 'float' in dtype_str:
        return 'double precision'
    elif 'bool' in dtype_str:
        return 'boolean'
    else:
        return 'text'

def generar_script_sql():
    carpeta_datos = 'correcciones'
    
    # Buscar archivos .xlsx
    archivos_excel = glob.glob(os.path.join(carpeta_datos, '*.xlsx'))
    
    if not archivos_excel:
        print(f"❌ No se encontraron archivos Excel (.xlsx) en la carpeta: {carpeta_datos}/")
        return

    sql_final = []
    sql_final.append("-- ==========================================================")
    sql_final.append("-- SCRIPT DE CREACIÓN MASIVA DE TABLAS (VIVAS E HISTÓRICAS)")
    sql_final.append("-- Generado automáticamente para Supabase desde Excel")
    sql_final.append("-- ==========================================================\n")

    for ruta in archivos_excel:
        nombre_archivo = os.path.basename(ruta)
        
        # 1. Limpiar el nombre de la tabla (Quitar el "_26062025.xlsx")
        # Esto busca un guion bajo seguido de 8 números y la extensión .xlsx para borrarlo
        nombre_base = re.sub(r'_\d{8}\.xlsx$', '', nombre_archivo)
        # Porcentaje de seguridad por si el nombre no tiene ese patrón exacto
        nombre_base = nombre_base.replace('.xlsx', '')
        
        print(f"⏳ Analizando: {nombre_archivo} -> Mapeado a tabla: {nombre_base}")

        try:
            # 2. Leer Excel (se usa read_excel, y nrows funciona en versiones recientes de pandas)
            df = pd.read_excel(ruta, nrows=100)
            
            definicion_columnas = []
            
            # 3. Columna ID autoincremental
            definicion_columnas.append("  id bigint generated by default as identity not null")
            
            # 4. Columnas dinámicas de la data cruda
            for col in df.columns:
                col_limpia = limpiar_nombre_columna(col)
                
                # REGLA DE ORO: Evitar colisión de IDs
                if col_limpia == 'id':
                    col_limpia = 'id_original'
                    
                tipo_sql = mapear_tipo_sql(df[col].dtype)
                definicion_columnas.append(f"  {col_limpia} {tipo_sql} null")
            
            # 5. Columnas de Gobernanza ETL
            definicion_columnas.append("  etl_origen_archivo text null")
            definicion_columnas.append("  etl_lote_ejecucion text null")
            definicion_columnas.append("  etl_fecha_carga_col text null")
            
            # 6. Generar ambas tablas (Normal e Histórica)
            for prefijo in ['', 'hist_']:
                nombre_tabla = f"{prefijo}{nombre_base}"
                restriccion_pk = f"  constraint {nombre_tabla}_pkey primary key (id)"
                
                # Unir todas las partes
                todas_las_lineas = ",\n".join(definicion_columnas + [restriccion_pk])
                
                query = f"create table public.{nombre_tabla} (\n{todas_las_lineas}\n) TABLESPACE pg_default;\n"
                sql_final.append(query)
                
        except Exception as e:
            print(f"❌ Error al procesar {nombre_archivo}: {e}")

    # Guardar todo en un archivo SQL
    nombre_salida = 'creacion_tablas_supabase.sql'
    with open(nombre_salida, 'w', encoding='utf-8') as archivo_sql:
        archivo_sql.write("\n".join(sql_final))
        
    print(f"\n✅ ¡BINGO! Se ha creado el archivo '{nombre_salida}'.")
    print("👉 Ábrelo, copia todo el texto y pégalo en el SQL Editor de Supabase para ejecutarlo.")

if __name__ == "__main__":
    generar_script_sql()